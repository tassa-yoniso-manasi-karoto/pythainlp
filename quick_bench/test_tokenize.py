def calculate_tokenization_accuracy(reference, hypothesis):
    """Calculate accuracy metrics between reference and hypothesis tokenizations"""
    ref_set = set(reference)
    hyp_set = set(hypothesis)
    
    # For position-sensitive accuracy
    matches = 0
    ref_idx = 0
    hyp_idx = 0
    ref_text = ''.join(reference)
    hyp_text = ''.join(hypothesis)
    
    # Simple position matching
    while ref_idx < len(reference) and hyp_idx < len(hypothesis):
        if reference[ref_idx] == hypothesis[hyp_idx]:
            matches += 1
            ref_idx += 1
            hyp_idx += 1
        else:
            # Try to resync
            if ref_idx + 1 < len(reference) and reference[ref_idx + 1] == hypothesis[hyp_idx]:
                ref_idx += 1
            elif hyp_idx + 1 < len(hypothesis) and reference[ref_idx] == hypothesis[hyp_idx + 1]:
                hyp_idx += 1
            else:
                ref_idx += 1
                hyp_idx += 1
    
    # Calculate metrics
    true_positives = len(ref_set & hyp_set)
    precision = true_positives / len(hyp_set) if hyp_set else 0
    recall = true_positives / len(ref_set) if ref_set else 0
    f1 = 2 * (precision * recall) / (precision + recall) if (precision + recall) > 0 else 0
    
    # Position-based accuracy
    position_accuracy = matches / max(len(reference), len(hypothesis))
    
    # Check if texts match (important!)
    text_preserved = ref_text == hyp_text
    
    return {
        'precision': precision,
        'recall': recall,
        'f1': f1,
        'position_accuracy': position_accuracy,
        'exact_matches': matches,
        'ref_tokens': len(reference),
        'hyp_tokens': len(hypothesis),
        'text_preserved': text_preserved
    }

