def warm_up(engine='newmm', iterations=5):
    """Warm up the tokenizer"""
    print(f"Warming up {engine}...", end='', flush=True)
    
    # Set timeout for warmup
    if hasattr(signal, 'SIGALRM'):
        signal.signal(signal.SIGALRM, timeout_handler)
        signal.alarm(10)  # 10 second timeout for warmup
    
    try:
        for _ in range(iterations):
            word_tokenize("ทดสอบระบบการตัดคำภาษาไทย", engine=engine)
        print(" done")
        return True
    except TimeoutException:
        print(" TIMEOUT")
        return False
    except Exception as e:
        print(f" FAILED: {type(e).__name__}: {str(e)[:50]}")
        return False
    finally:
        if hasattr(signal, 'SIGALRM'):
            signal.alarm(0)  # Cancel timeout

def benchmark_single(text, engine, iterations=10):
    """Benchmark a single text with specific engine"""
    times = []
    
    for i in range(iterations):
        try:
            start = time.perf_counter()
            result = word_tokenize(text, engine=engine)
            end = time.perf_counter()
            times.append(end - start)
        except Exception as e:
            print(f"\n  Error in iteration {i+1}: {e}")
            if len(times) < 3:  # Need at least 3 successful runs
                raise
            break
    
    if not times:
        raise Exception("No successful runs")
    
    return {
        'mean': statistics.mean(times),
        'median': statistics.median(times),
        'stdev': statistics.stdev(times) if len(times) > 1 else 0,
        'min': min(times),
        'max': max(times),
        'tokens': len(result),
        'chars': len(text),
        'times': times,
        'runs': len(times)
    }

